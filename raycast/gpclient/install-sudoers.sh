#!/bin/bash
# Install a sudoers drop-in so Raycast can run gpclient and gp-disconnect
# without a password prompt.
# Review the file, then run: bash raycast/gpclient/install-sudoers.sh
set -euo pipefail

USER_NAME="${SUDO_USER:-$USER}"
ARM="/opt/homebrew/bin/gpclient"
INTEL="/usr/local/bin/gpclient"
STOP="/opt/homebrew/bin/gp-disconnect"
DEST="/etc/sudoers.d/gpclient"
TMP="$(mktemp)"
HERE="$(cd "$(dirname "$0")" && pwd)"

# gp-disconnect is a small kill wrapper; a second `gpclient` is SIGKILL'd
# while a tunnel is up (exit 137).
install -m 755 "$HERE/gp-disconnect.sh" "$STOP"

# Keep PATH so vpn-slice under Homebrew is still found when running as root.
{
  echo "# Generated by GlobalProtect-openconnect-macOS raycast/gpclient/install-sudoers.sh"
  echo "Defaults!${ARM} env_keep += \"PATH\""
  echo "Defaults!${INTEL} env_keep += \"PATH\""
  echo "Defaults!${STOP} env_keep += \"PATH\""
  echo "${USER_NAME} ALL=(root) NOPASSWD:SETENV: ${ARM}, ${INTEL}, ${STOP}"
} >"$TMP"

/usr/sbin/visudo -c -f "$TMP"
sudo install -m 440 "$TMP" "$DEST"
rm -f "$TMP"
echo "Installed ${DEST} and ${STOP}."
